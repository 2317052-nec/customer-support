// Statistical calculation functions for calibration
export function calculateCalibrationMetrics(data: CalibrationItem[]) {
  const n = data.length;
  if (n === 0) return { pearsonR: 0, cohensKappa: 0, agreementPct: 0, meanHuman: 0, meanLlm: 0 };

  // Pearson correlation between human_score and llm_score (scale 1-5)
  let sumH = 0;
  let sumL = 0;
  let sumH2 = 0;
  let sumL2 = 0;
  let sumHL = 0;

  // Cohen's Kappa for categorical action agreement (AUTO_REPLY vs ESCALATE)
  let agreeActionCount = 0;
  let humanAuto = 0;
  let humanEsc = 0;
  let llmAuto = 0;
  let llmEsc = 0;

  for (const item of data) {
    sumH += item.human_score;
    sumL += item.llm_score;
    sumH2 += item.human_score * item.human_score;
    sumL2 += item.llm_score * item.llm_score;
    sumHL += item.human_score * item.llm_score;

    if (item.human_action === item.llm_action) {
      agreeActionCount++;
    }
    if (item.human_action === 'AUTO_REPLY') humanAuto++;
    else humanEsc++;

    if (item.llm_action === 'AUTO_REPLY') llmAuto++;
    else llmEsc++;
  }

  const numerator = n * sumHL - sumH * sumL;
  const denom = Math.sqrt((n * sumH2 - sumH * sumH) * (n * sumL2 - sumL * sumL));
  const pearsonR = denom === 0 ? 0 : numerator / denom;

  // Observed agreement (Po)
  const Po = agreeActionCount / n;

  // Expected chance agreement (Pe)
  const pHumanAuto = humanAuto / n;
  const pHumanEsc = humanEsc / n;
  const pLlmAuto = llmAuto / n;
  const pLlmEsc = llmEsc / n;

  const Pe = (pHumanAuto * pLlmAuto) + (pHumanEsc * pLlmEsc);
  const cohensKappa = Pe === 1 ? 1 : (Po - Pe) / (1 - Pe);

  return {
    pearsonR: Number(pearsonR.toFixed(4)),
    cohensKappa: Number(cohensKappa.toFixed(4)),
    agreementPct: Number((Po * 100).toFixed(1)),
    meanHuman: Number((sumH / n).toFixed(2)),
    meanLlm: Number((sumL / n).toFixed(2)),
  };
}
